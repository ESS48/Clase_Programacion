    private void btnInsertarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInsertarActionPerformed

        try {
            String titulo = txtTitulo.getText().trim();
            if (titulo.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Debes meter un titulo", "error", JOptionPane.ERROR_MESSAGE);
            }

            String precio = txtPrecio.getText().trim();
            double precios = Double.parseDouble(precio);
            String Stock = txtStock.getText().trim();
            int Stocks = Integer.parseInt(Stock);

            Videojuego v = new Videojuego(titulo, cmbPlataforma.getSelectedItem().toString(), precios, Stocks);

            boolean insertar = dao.insertar(v);

            if (insertar == true) {
                System.out.println("Se inserto correctamente");

            } else {
                System.out.println("No se inserto nada");
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Debes meter numeros", "error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnInsertarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed

        try {

            Videojuego v = lstVideojuegos.getSelectedValue();

            if (v == null) {
                JOptionPane.showMessageDialog(this, "Debes seleccionar un videojuego", "Error", JOptionPane.ERROR_MESSAGE);
            } else {

                String titulo = txtTitulo.getText().trim();
                if (titulo.isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Debes meter un titulo", "error", JOptionPane.ERROR_MESSAGE);
                }

                String precio = txtPrecio.getText().trim();
                double precios = Double.parseDouble(precio);
                String Stock = txtStock.getText().trim();
                int stocks = Integer.parseInt(Stock);
                String i = txtId.getText().trim();
                int id = Integer.parseInt(i);

                Videojuego cambio = new Videojuego(id,titulo, cmbPlataforma.getSelectedItem().toString(), precios, stocks);

                boolean actualizar = dao.actualizar(cambio);

                if (actualizar == true) {
                    System.out.println("Se actualizo correctamente");
                    cargarB();

                } else {
                    System.out.println("No se actualizo nada");
                }
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Debes meter numeros", "error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed

        try {

            Videojuego v = lstVideojuegos.getSelectedValue();
            
            if (v == null) {
                JOptionPane.showMessageDialog(this, "Debes seleccionar un videojuego", "Error", JOptionPane.ERROR_MESSAGE);
            } else {

                String i = txtId.getText().trim();
                int id = Integer.parseInt(i);

                boolean eliminar = dao.eliminar(id);

                if (eliminar == true) {
                    System.out.println("Se elimino correctamente");
                    cargarB();

                } else {
                    System.out.println("No se actualizo nada");
                }
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Debes meter numeros", "error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnEliminarActionPerformed

