    private void lstVideojuegosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_lstVideojuegosMouseClicked
        // TODO add your handling code here:7

        Videojuego v = lstVideojuegos.getSelectedValue();

        if (v == null) {
            System.out.println("Selecciona un videojuego");
        } else {

            int id = v.getId();
            String i = String.valueOf(id);

            String titulo = v.getTitulo();
            String plataforma = v.getPlataforma();

            double precio = v.getPrecio();
            String p = String.valueOf(precio);
            int stock = v.getStock();
            String s = String.valueOf(stock);

            txtId.setText(i);
            txtTitulo.setText(titulo);
            txtPrecio.setText(p);
            txtStock.setText(s);

        }
    }//GEN-LAST:event_lstVideojuegosMouseClicked

    public void cargarB() {
        modeloLista.clear();

        ArrayList<Videojuego> listar = dao.listar();

        for (Videojuego l : listar) {
            modeloLista.addElement(l);
        }
    }

